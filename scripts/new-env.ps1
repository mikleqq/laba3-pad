<#
.SYNOPSIS
    Creates the .env file with random secrets (used by Docker Compose and by the Kubernetes Secret).

.DESCRIPTION
    .env is listed in .gitignore, so the real secrets never get into Git.
    Kubernetes: scripts\k8s-secret.ps1 turns the same file into the Secret "shophub-secrets".

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\new-env.ps1
    powershell -ExecutionPolicy Bypass -File scripts\new-env.ps1 -Force   # overwrite an existing .env
#>
param([switch]$Force)

$root = Split-Path $PSScriptRoot -Parent
$path = Join-Path $root ".env"
if ((Test-Path $path) -and -not $Force) {
    Write-Host ".env already exists (use -Force to regenerate it)" -ForegroundColor Yellow
    exit 0
}

function New-Secret([int]$Length = 32) {
    $chars = [char[]]"ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789"
    $bytes = New-Object byte[] $Length
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}

$lines = @(
    "# Generated by scripts\new-env.ps1 - DO NOT COMMIT (listed in .gitignore)",
    "POSTGRES_PASSWORD=$(New-Secret)",
    "AUTH_DB_PASSWORD=$(New-Secret)",
    "USER_DB_PASSWORD=$(New-Secret)",
    "PRODUCT_DB_PASSWORD=$(New-Secret)",
    "ORDER_DB_PASSWORD=$(New-Secret)",
    "PAYMENT_DB_PASSWORD=$(New-Secret)",
    "NOTIFICATION_DB_PASSWORD=$(New-Secret)",
    "JWT_SECRET=$(New-Secret 48)",
    "INTERNAL_TOKEN=$(New-Secret 40)",
    "ADMIN_PASSWORD=Admin$(New-Secret 10)1"
)
[System.IO.File]::WriteAllLines($path, $lines)
Write-Host "Created $path with random secrets." -ForegroundColor Green
Write-Host "Administrator login: admin@example.com / $((($lines | Where-Object { $_ -like 'ADMIN_PASSWORD=*' }) -split '=', 2)[1])"
